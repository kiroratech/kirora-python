"""Regenerates the SDK's typed models, error codes, webhook event names and retry table
from Kirora's OpenAPI spec:

    python scripts/codegen.py [path/to/openapi.json]
    python scripts/codegen.py --check [path/to/openapi.json]

By default the spec is downloaded from the commit of github.com/kiroratech/openapi named
in ``spec/source.json``, and must match its ``version`` and ``sha256``. A local path, or
``KIRORA_OPENAPI_SPEC``, is used instead without those checks, for trying out a spec that
isn't published yet. With ``--check``, nothing is written: it exits with 1 if any
generated file is out of date.

A download is cached in ``.cache/kirora-openapi``, under its checksum, so later runs work
offline. Uses the standard library only.
"""

