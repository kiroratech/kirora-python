def fail(message: str) -> None:
    sys.stderr.write(message + "\n")
    sys.exit(1)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def load_spec(spec_arg: str | None) -> tuple[dict[str, Any], str]:
    source = json.loads((ROOT / "spec" / "source.json").read_text())
    if spec_arg is not None:
        return json.loads(Path(spec_arg).read_text()), spec_arg
    cache_dir = ROOT / ".cache" / "kirora-openapi"
    cached = cache_dir / f"{source['sha256']}.json"
    data: bytes | None = None
    downloaded = False
    if cached.exists():
        candidate = cached.read_bytes()
        if sha256(candidate) == source["sha256"]:
            data = candidate
    if data is None:
        with urllib.request.urlopen(source["url"], timeout=60) as response:
            data = response.read()
        downloaded = True
    spec = json.loads(data)
    digest = sha256(data)
    if digest != source["sha256"] or spec["info"]["version"] != source["version"]:
        fail(
            f"{source['url']} doesn't match spec/source.json. Set its version to "
            f"{spec['info']['version']} and its sha256 to {digest}."
        )
    if downloaded:
        cache_dir.mkdir(parents=True, exist_ok=True)
        cached.write_bytes(data)
    return spec, source["url"]


def deref(spec: dict[str, Any], ref: str) -> Any:
    node: Any = spec
    for key in ref.split("/")[1:]:
        node = node[key]
    return node


def resolve(spec: dict[str, Any], value: Any) -> Any:
    while isinstance(value, dict) and isinstance(value.get("$ref"), str):
        value = deref(spec, value["$ref"])
    return value


def operation_parameters(spec: dict[str, Any], item: dict[str, Any], operation: dict[str, Any]) -> list[Any]:
    """An operation's parameters: those declared on its path, for all its operations,
    then its own."""
    return [resolve(spec, p) for p in item.get("parameters", []) + operation.get("parameters", [])]


# --- Retry table -----------------------------------------------------------------------


def operations_file(spec: dict[str, Any]) -> str:
    for kind in RETRY_KINDS:
        if kind not in spec.get("x-retry-kinds", {}):
            fail(f'x-retry-kinds no longer has "{kind}": update _retry.py and RETRY_KINDS')
    lines = []
    for path in sorted(spec["paths"]):
        item = spec["paths"][path]
        for method in ["get", "put", "post", "patch", "delete"]:
            operation = item.get(method)
            if not operation:
                continue
            retry = operation.get("x-retry", "read" if method == "get" else None)
            if retry is not None and retry not in RETRY_KINDS:
                fail(f'{method} {path}: unknown x-retry "{retry}": update _retry.py')
            parameters = operation_parameters(spec, item, operation)
            accepts_key = any(
                p.get("in") == "header" and p.get("name", "").lower() == "idempotency-key" for p in parameters
            )
            entries = None
            if retry == "entries":
                body = resolve(
                    spec,
                    operation.get("requestBody", {})
                    .get("content", {})
                    .get("application/json", {})
                    .get("schema"),
                )
                for name in sorted((body or {}).get("properties", {})):
                    prop = resolve(spec, body["properties"][name])
                    items = resolve(spec, prop.get("items"))
                    if prop.get("type") == "array" and "idempotencyKey" in (items or {}).get(
                        "properties", {}
                    ):
                        entries = name
                        break
                if entries is None:
                    fail(f"{method} {path}: x-retry is entries, but no array in its body has idempotencyKey")
            lines.append(
                f'    "{method.upper()} {path}": Operation('
                f'"{operation["operationId"]}", {py(retry)}, {accepts_key}, {py(entries)}),\n'
            )
    return (
        f"{HEADER}\nfrom __future__ import annotations\n\n"
        "from typing import Dict, NamedTuple, Optional\n\n"
        "class Operation(NamedTuple):\n"
        '    """How an operation may be retried, from the spec\'s ``x-retry``."""\n\n'
        "    id: str\n"
        "    retry: Optional[str]\n"
        "    accepts_key: bool\n"
        "    entries: Optional[str]\n\n\n"
        f"OPERATIONS: Dict[str, Operation] = {{\n{''.join(lines)}}}\n"
    )


def py(value: str | None) -> str:
    """A string or None as Python source."""
    return "None" if value is None else json.dumps(value)


# --- Models ----------------------------------------------------------------------------


def pascal(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    return "".join(part[:1].upper() + part[1:] for part in parts if part)


def singular(name: str) -> str:
    if name.endswith("ies"):
        return name[:-3] + "y"
    if name.endswith("ses") or name.endswith("xes"):
        return name[:-2]
    if name.endswith("s") and not name.endswith("ss"):
        return name[:-1]
    return name + "Item"


def doc_text(schema: dict[str, Any]) -> str:
    return (schema.get("description") or schema.get("title") or "").strip()


# The names the models file imports, which no model may take. Lists and maps are written
# as the builtins `list` and `dict`, since the API has a `List` schema.
TYPING_NAMES = {
    "Any",
    "Optional",
    "Union",
    "Literal",
    "NotRequired",
    "Required",
    "TypedDict",
    "final",
    "date",
    "datetime",
}


class Models:
    """Turns schemas into TypedDicts and type aliases, declared by name."""

    def __init__(self, spec: dict[str, Any]) -> None:
        self.spec = spec
        # Name to its source text.
        self.decls: dict[str, str] = {}
        self.in_progress: set[str] = set()
        # TypedDicts in a union, made final so a type checker can narrow the union on a
        # key, as with `"error" in entry`. The rest stay open to keys the API adds.
        self.union_members: set[str] = set()

    # Each type expression is written with names quoted, so it can be used anywhere,
    # including in runtime-evaluated aliases that refer to later declarations.
    def ref(self, ref: str) -> str:
        return self.declare(ref.split("/")[-1], deref(self.spec, ref))

    def declare(self, name: str, schema: dict[str, Any]) -> str:
        """Declares ``name`` as ``schema``, and returns the quoted name."""
        if name in self.decls or name in self.in_progress:
            return mark(name)
        self.in_progress.add(name)
        schema_nn, _ = self.non_null(schema)
        if self.is_object(schema_nn):
            self.decls[name] = self.typed_dict(name, schema_nn)
        else:
            expr = self.type_of(schema_nn, name)
            doc = doc_text(schema)
            text = f"{name} = {quoted(expr)}\n"
            if doc:
                text += f'"""{escape_doc(doc)}"""\n'
            self.decls[name] = text
        self.in_progress.discard(name)
        return mark(name)

    def non_null(self, schema: dict[str, Any]) -> tuple[dict[str, Any], bool]:
        types = schema.get("type")
        if isinstance(types, list) and "null" in types:
            rest = [t for t in types if t != "null"]
            copy = dict(schema)
            copy["type"] = rest[0] if len(rest) == 1 else rest
            if not rest:
                copy.pop("type")
            return copy, True
        if schema.get("type") == "null":
            return {}, True
        for key in ("anyOf", "oneOf"):
            variants = schema.get(key)
            if isinstance(variants, list):
                kept = [v for v in variants if resolve(self.spec, v).get("type") != "null"]
                if len(kept) != len(variants):
                    copy = {k: v for k, v in schema.items() if k != key}
                    if len(kept) == 1:
                        merged = dict(kept[0])
                        for k, v in copy.items():
                            merged.setdefault(k, v)
                        return merged, True
                    copy[key] = kept
                    return copy, True
        return schema, False

    def is_object(self, schema: dict[str, Any]) -> bool:
        return (schema.get("type") == "object" or "properties" in schema) and bool(schema.get("properties"))

    def type_of(self, schema: Any, hint: str) -> str:
        hint = RENAMES.get(hint, hint)
        if schema is True or schema == {}:
            return "Any"
        if not isinstance(schema, dict):
            return "Any"
        if "$ref" in schema:
            return self.ref(schema["$ref"])
        inner, nullable = self.non_null(schema)
        if nullable:
            return f"Optional[{self.type_of(inner, hint)}]"
        if "const" in schema:
            return f"Literal[{literal(schema['const'])}]"
        if "enum" in schema:
            values = f"Literal[{', '.join(literal(v) for v in schema['enum'] if v is not None)}]"
            if hint not in NAMED_ENUMS:
                return values
            name = NAMED_ENUMS[hint]
            if self.decls.setdefault(name, f"{name} = {values}\n") != f"{name} = {values}\n":
                fail(f"{hint}'s values differ from those of {name}: update NAMED_ENUMS")
            return mark(name)
        for key in ("anyOf", "oneOf"):
            if key in schema:
                return self.union(schema[key], hint)
        types = schema.get("type")
        if isinstance(types, list):
            return f"Union[{', '.join(self.type_of({'type': t}, hint) for t in types)}]"
        if types == "string":
            return "str"
        if types == "integer":
            return "int"
        if types == "number":
            return "float"
        if types == "boolean":
            return "bool"
        if types == "array":
            return f"list[{self.type_of(schema.get('items', {}), singular(hint))}]"
        if types == "object" or "properties" in schema:
            if schema.get("properties"):
                return self.declare(hint, schema)
            extra = schema.get("additionalProperties", True)
            value = "Any" if extra in (True, False) else self.type_of(extra, hint + "Value")
            return f"dict[str, {value}]"
        return "Any"

    def union(self, variants: list[Any], hint: str) -> str:
        flat: list[Any] = []

        def add(variant: Any) -> None:
            for key in ("anyOf", "oneOf"):
                if isinstance(variant, dict) and key in variant and "$ref" not in variant:
                    for v in variant[key]:
                        add(v)
                    return
            flat.append(variant)

        for v in variants:
            add(v)
        # Strings only, as consts or enums, make one Literal.
        literals: list[str] = []
        if all(isinstance(v, dict) and "$ref" not in v and ("const" in v or "enum" in v) for v in flat):
            for v in flat:
                for value in [v["const"]] if "const" in v else v["enum"]:
                    if literal(value) not in literals:
                        literals.append(literal(value))
            return f"Literal[{', '.join(literals)}]"
        parts: list[str] = []
        for index, v in enumerate(flat):
            part = self.type_of(v, f"{hint}{self.variant_name(v, index, flat)}")
            if part not in parts:
                parts.append(part)
            if part.startswith("\x01"):
                self.union_members.add(bare(part))
        if len(parts) == 1:
            return parts[0]
        return f"Union[{', '.join(parts)}]"

    def variant_name(self, variant: dict[str, Any], index: int, siblings: list[Any]) -> str:
        """Names an inline object variant: by its title, its constant tag such as
        ``type: "email"``, or the required property that sets it apart."""
        if "$ref" in variant:
            return ""
        if variant.get("title"):
            return pascal(variant["title"])
        props = variant.get("properties") or {}
        for prop in props.values():
            if isinstance(prop, dict) and isinstance(prop.get("const"), str):
                return pascal(prop["const"])
        required = variant.get("required", [])
        if "error" in required:
            return "Error"
        others = [set(resolve(self.spec, s).get("required", [])) for s in siblings if s is not variant]
        if any("error" in o for o in others):
            return "Success"
        for name in required:
            if all(name not in o for o in others):
                return pascal(name) if name in ("all", "any") else "By" + pascal(name)
        return f"Variant{index + 1}"

    def typed_dict(self, name: str, schema: dict[str, Any]) -> str:
        required = set(schema.get("required", []))
        props = schema["properties"]
        fields: list[tuple[str, str, str]] = []
        for prop_name, prop in props.items():
            expr = self.type_of(prop, name + pascal(prop_name))
            wrapper = "Required" if prop_name in required else "NotRequired"
            doc = doc_text(resolve(self.spec, prop)) if isinstance(prop, dict) else ""
            if isinstance(prop, dict) and prop.get("description"):
                doc = prop["description"].strip()
            fields.append((prop_name, f"{wrapper}[{expr}]", doc))
        return typed_dict_text(name, doc_text(schema), fields)

    def query_params(self, operation: dict[str, Any], parameters: list[Any]) -> None:
        """Declares ``{OperationId}Params``, the operation's query parameters, as resource
        methods take them. ``idType`` is left out: methods take it as ``id_type``."""
        fields: list[tuple[str, str, str]] = []
        for parameter in parameters:
            if parameter.get("in") != "query" or parameter["name"] == "idType":
                continue
            wrapper = "Required" if parameter.get("required") else "NotRequired"
            fields.append(
                (parameter["name"], f"{wrapper}[{self.query_type(parameter)}]", doc_text(parameter))
            )
        if fields:
            name = pascal(operation["operationId"]) + "Params"
            self.decls[name] = typed_dict_text(
                name, f"Query parameters of ``{operation['operationId']}``.", fields
            )

    def query_type(self, parameter: dict[str, Any]) -> str:
        schema = resolve(self.spec, parameter.get("schema", {}))
        # A boolean filter is the string "true" or "false" in the query.
        if schema.get("type") == "string" and sorted(schema.get("enum", [])) == ["false", "true"]:
            return "bool"
        formats = {resolve(self.spec, v).get("format") for v in schema.get("anyOf", [schema])}
        if formats == {"date", "date-time"}:
            return "Union[str, date, datetime]"
        if formats == {"date-time"}:
            return "Union[str, datetime]"
        if formats == {"date"}:
            return "Union[str, date]"
        return self.type_of(schema, pascal(parameter["name"]))

    def models_file(self) -> str:
        names = sorted(self.decls)
        clash = TYPING_NAMES.intersection(names)
        if clash:
            fail(f"Schemas named like the typing helpers models.py imports: {sorted(clash)}")
        body = "\n\n".join(
            ("@final\n" if n in self.union_members and self.decls[n].startswith("class ") else "")
            + self.decls[n].rstrip("\n")
            + "\n"
            for n in names
        )
        exports = "".join(f'    "{n}",\n' for n in names)
        return (
            f"{HEADER}\n"
            "# Every model is a TypedDict: at runtime a plain dict, keyed by the API's own\n"
            "# camelCase field names. Fields the API adds later come through as extra keys.\n"
            "from __future__ import annotations\n\n"
            "from datetime import date, datetime\n"
            "from typing import Any, Optional, Union\n\n"
            "from typing_extensions import Literal, NotRequired, Required, TypedDict, final\n\n"
            f"__all__ = [\n{exports}]\n\n\n{body}"
        )


def typed_dict_text(name: str, doc: str, fields: list[tuple[str, str, str]]) -> str:
    """A TypedDict of ``fields``, each a name, a type and a description. Written as a
    class, or called as a function when a name can't be an attribute, such as ``from``."""
    if any(not n.isidentifier() or keyword.iskeyword(n) for n, _, _ in fields):
        body = "".join(f"        {json.dumps(n)}: {quoted(t)},\n" for n, t, _ in fields)
        text = f'{name} = TypedDict(\n    "{name}",\n    {{\n{body}    }},\n    total=False,\n)\n'
        if doc:
            text += f'"""{escape_doc(doc)}"""\n'
        return text
    lines = [f"class {name}(TypedDict, total=False):\n"]
    if doc:
        lines.append(f'    """{escape_doc(doc)}"""\n\n')
    for n, t, field_doc in fields:
        # Annotations are lazy, so a class body can name later declarations bare.
        lines.append(f"    {n}: {bare(t)}\n")
        if field_doc:
            lines.append(f'    """{escape_doc(field_doc)}"""\n')
    if not fields:
        lines.append("    pass\n")
    return "".join(lines)


def literal(value: Any) -> str:
    """A JSON constant as a Python literal, for ``Literal[...]``."""
    if isinstance(value, str):
        return json.dumps(value)
    return repr(value)


def mark(name: str) -> str:
    return f"\x01{name}\x02"


def quoted(expr: str) -> str:
    return re.sub("\x01([^\x02]*)\x02", r'"\1"', expr)


def bare(expr: str) -> str:
    return re.sub("\x01([^\x02]*)\x02", r"\1", expr)


def escape_doc(text: str) -> str:
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if text.endswith('"'):
        text += " "
    return text


def prune_and_generate(spec: dict[str, Any]) -> str:
    models = Models(spec)
    wrapped = [
        (item, operation)
        for item in spec["paths"].values()
        for operation in item.values()
        if isinstance(operation, dict) and operation.get("operationId") in OPERATIONS
    ]
    missing = set(OPERATIONS) - {operation["operationId"] for _, operation in wrapped}
    if missing:
        fail(f"Not in the spec: {', '.join(sorted(missing))}")

    def visit(value: Any) -> None:
        if isinstance(value, list):
            for v in value:
                visit(v)
        elif isinstance(value, dict):
            if isinstance(value.get("$ref"), str) and value["$ref"].startswith("#/components/schemas/"):
                models.ref(value["$ref"])
                return
            for key, v in value.items():
                if key in ("examples", "example"):
                    continue
                visit(v)

    for item, operation in wrapped:
        visit(operation.get("requestBody"))
        visit(operation.get("responses"))
        models.query_params(operation, operation_parameters(spec, item, operation))
    visit(spec["webhooks"])
    models.ref("#/components/schemas/ErrorCode")
    models.ref("#/components/schemas/FieldError")
    return models.models_file()


def const_tuple(name: str, values: list[str]) -> str:
    body = "".join(f'    "{v}",\n' for v in values)
    return f"{HEADER}\nfrom typing import Tuple\n\n{name}: Tuple[str, ...] = (\n{body})\n"


def main() -> None:
    args = sys.argv[1:]
    check = "--check" in args
    rest = [a for a in args if a != "--check"]
    spec_arg = rest[0] if rest else os.environ.get("KIRORA_OPENAPI_SPEC") or None
    spec, spec_name = load_spec(spec_arg)
    error_codes = spec["components"]["schemas"]["ErrorCode"]["enum"]
    webhook_events = list(spec["webhooks"])
    outputs = {
        PACKAGE / "_error_codes.py": const_tuple("ERROR_CODES", error_codes),
        PACKAGE / "_webhook_events.py": const_tuple("WEBHOOK_EVENTS", webhook_events),
        PACKAGE / "_operations.py": operations_file(spec),
        PACKAGE / "types.py": prune_and_generate(spec),
    }
    if check:
        stale = [
            str(path.relative_to(ROOT))
            for path, content in outputs.items()
            if not path.exists() or path.read_text() != content
        ]
        if stale:
            fail(f"Out of date with {spec_name}: {', '.join(stale)}. Run `python scripts/codegen.py`.")
        print("Generated files are up to date")
        return
    for path, content in outputs.items():
        path.write_text(content)
    print(
        f"Wrote {len(error_codes)} error codes, {len(webhook_events)} webhook events, "
        "the models and the retry table"
    )


if __name__ == "__main__":
    main()
